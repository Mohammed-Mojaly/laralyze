<?php

/*
 * Refresh resources/ai-prices.php, the AI prices Laralyze ships, from
 * OpenRouter. Run `composer prices` before a release.
 */

use MohammedMojaly\Laralyze\Support\AiPrices;

require __DIR__.'/../vendor/autoload.php';

$lists = array_map(function (string $url) {
    $json = file_get_contents($url, context: stream_context_create(['http' => ['timeout' => 30]]));

    return json_decode((string) $json, true, flags: JSON_THROW_ON_ERROR);
}, AiPrices::SOURCES);

$prices = AiPrices::fromOpenRouter(...$lists);

$lines = array_map(
    fn (string $name, array $price) => '    '.var_export($name, true).' => ['.implode(', ', array_map(fn ($value) => $value === null ? 'null' : rtrim(rtrim(sprintf('%.6F', $value), '0'), '.'), $price)).'],',
    array_keys($prices),
    $prices,
);

file_put_contents(__DIR__.'/../resources/ai-prices.php', implode("\n", [
    '<?php',
    '',
    '// USD per million tokens: input, output, cache read, cache write.',
    '// From '.implode(' and ', AiPrices::SOURCES).' on '.date('Y-m-d').'.',
    '// Generated by bin/ai-prices.php; run `composer prices` to refresh.',
    '',
    'return [',
    ...$lines,
    '];',
    '',
]));

echo count($prices)." prices written.\n";
